	// a new clip window (new song / HUD): find the effect sprites among its siblings by their texture names
	void discover(void *clip, void *fill)
	{
		g_sp = StarPower();
		g_sp.clip = clip;
		g_sp.fill = fill;
		g_sp.parent = *reinterpret_cast<void **>(field(clip, kElementParent));
		if (!g_sp.parent)
			return;
		for (void *a = g_sp.parent; a; a = *reinterpret_cast<void **>(field(a, kElementParent)))
			g_sp.rot += f32(a, kElementRot);
		g_sp.fill_rot0 = f32(fill, kElementRot);
		log("star power tube %p: ancestors' rotation %.3f deg", clip, g_sp.rot * 57.2957795f);
		int bursts = 0;
		for (void *e = *reinterpret_cast<void **>(field(g_sp.parent, kElementFirstChild)); e;
		     e = *reinterpret_cast<void **>(field(e, kElementNextSibling)))
		{
			const uint32_t t = texture_of(e);
			for (int k = 0; k < 3; ++k)
				if (t == kGlowTex[k])
					g_sp.glow[k] = e;
			if (t == kBall[0] && bursts < 3)
				g_sp.burst[bursts++] = e;
			if (t == kStarBar)
				g_sp.star_bar = e;
			else if (t == kStarLead)
				g_sp.star_lead = e;
			else if (t == kProgFill)
				g_sp.prog_fill = e;
			else if (t == kProgLead)
				g_sp.prog_lead = e;
			else if (t == kStarFire[0])
				g_sp.star_fire = e;
			void *child = *reinterpret_cast<void **>(field(e, kElementFirstChild));
			if (e != clip && child && texture_of(child) == kSpFull && g_sp.feathers < kFeathers)
				g_sp.feather[g_sp.feathers++] = e;
		}
		bool ok = bursts == 3;
		for (void *g : g_sp.glow)
			ok = ok && g && f32(g, kElementAlpha) == 0.0f;       // the desc starts them hidden
		ok = ok && f32(g_sp.parent, kElementAlpha) == 1.0f;       // and their container visible
		g_sp.effects = ok;
		log("star power effects: %s (glows %p %p %p, bursts %d, feathers %d)", ok ? "found" : "not found, fill only",
		    g_sp.glow[0], g_sp.glow[1], g_sp.glow[2], bursts, g_sp.feathers);
		log("score box effects: star bar %p lead %p, song line %p lead %p, star fire %p", g_sp.star_bar, g_sp.star_lead,
		    g_sp.prog_fill, g_sp.prog_lead, g_sp.star_fire);
	}

