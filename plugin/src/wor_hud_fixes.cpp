// wor_hud_fixes.asi: native HUD fixes for the GH5 / Warriors of Rock HUD theme (GHWT: Definitive Edition, x86).
// Loaded by Ultimate ASI Loader (dinput8.dll). In-memory patches only; every patch site is byte-checked first and
// the plugin stays inert on any mismatch (another game build, or other code already patching the same place).
// Log: <game folder>\wor_hud_fixes.log. Reverse-engineering notes: docs/PLUGIN_NOTES.md.
//
// Fix 1, note-streak lights (senotestreaklights widget, set_lights 0x476590): for the WoR theme's widgets
//   - WoR's colours: x1 pink, x2 orange, x3 green, x4 purple, star power blue (the DE shares one set for x1/x2);
//   - our own texture names (WoR_HUD_light_*), which the stock z_in_game textures can't shadow from the 2nd song on.
// WoR widgets are recognised by their first light element's texture (the desc starts it on WoR_HUD_light_0, and
// the plugin only ever sets WoR_HUD_light_* names on it). Every other widget runs the game's own code.
//
// Fix 2, star power fill: the SP tube widget (update at 0x478630) sets the stock fill names on its segments with
// two SetTexture calls. For segments that still carry one of our fill names (the desc starts them on it) the
// stock name is replaced by ours, so the stock textures can't shadow ours from the 2nd song on.
//
// Fix 3, theme switch crash (DE bug): the font unload function (0x6403b0) searches the loaded-font table with a loop
// whose end bound the DE patches to its enlarged table while the start stays the original 0xeecd60, so unloading a
// font that isn't in the first 32 slots (the WoR numeral font, shipped in our theme pak) runs off into unmapped
// memory. On its first call the unload loop is given the same bounds as the DE-patched font-add loop (0x640720).
//
// Fix 3b, theme switch crash (2026-10-06): with the bounds fixed, the unload went through, and the game then crashed
// drawing (ReShade d3d9 under DrawPrimitiveUP) after our font was freed with the theme pak. A font is not copied out
// of its pak: the font object IS the pak's file data (byte-swapped and relocated in place by 0x6b78b0, linked into
// the font list 0xfc1090), so the font can't outlive the pak. Our numeral font is therefore made resident: when the
// game loads it (0x640930, cdecl: checksum, data, 0, size, ...) the plugin hands it a private copy of the file data
// that is never freed, and its unload (0x6403b0) is skipped. The next load of the theme finds it already registered
// (0x640930 returns the existing font first). Stock themes ship no fonts, so nothing else changes.
//
// Fix 4, smooth star power fill: after the SP tube update (0x478630) runs, WoR tubes get one continuous fill instead
// of six stretched segments: segments 1-5 are scaled to 0, segment 0 becomes the full-length glass-shaped fill
// (WoR_HUD_spfull, or _b with lightning when the game picked the charged texture, i.e. >= 50% or active) and its
// parent clip window's top edge is moved to the charge level (0-50% bottom -> half divider, 50-100% -> top).
//
// Fix 5, GH5's star power lifecycle (docs/GH5_STAR_POWER_REFERENCE.md): the clip window's per-frame update
// (element update 0x5a2dd0) drives the effect sprites: below 50% the charging fill + WoR's soft bottom glow; ready
// (>= 50% or active) the WoR Mat_Sp_Ready_Fire look as a 60 fps loop (WoR_HUD_spplasma_*) + the white-hot cap at
// the fill top; crossing into ready, a ball-lightning burst (16 frames at 20 fps) at the fill top.
