	// battle_hud_2d_elements.rock_pos + card offsets (scale 1 / medium_scale / small_scale). The wrapper's $change$ of
	// those offsets never reached the cards (test 2026-10-21: they sat on the stock spots), so while our battle needle is
	// on screen each card's morph target is moved from the stock spot of its slot to our slot (kBSlot), and the card is
	// sized for that slot (dims = size / the scale the morph goes to).
	bool close_to(float x, float y, float px, float py) { return (x - px) * (x - px) + (y - py) * (y - py) < 4.0f; }

	void battle_card(void *card)
	{
		if (now() - g_battle_seen > 0.5)
			return;
		void *parent = *reinterpret_cast<void **>(field(card, kElementParent));
		if (!parent || id_of(parent) != kBattlemodeContainer)
			return;
		float &tx = f32(card, kElementPosTarget), &ty = f32(card, kElementPosTarget + 4);
		int slot = -1;
		for (int i = 0; i < 6 && slot < 0; ++i)
		{
			if (close_to(tx, ty, kBSlot[i][0], kBSlot[i][1]))
			{
				slot = i;
				if (close_to(f32(card, kElementPos), f32(card, kElementPos + 4), tx, ty))
				{
					f32(card, kElementPos) = kBSlot[i][2];      // already parked on the stock spot: jump
					f32(card, kElementPos + 4) = kBSlot[i][3];
				}
				tx = kBSlot[i][2];
				ty = kBSlot[i][3];
				if (g_bcards++ < 12)
					log("battle card %08x: slot %d moved to (%.0f, %.0f)", id_of(card), i, kBSlot[i][2], kBSlot[i][3]);
			}
			else if (close_to(tx, ty, kBSlot[i][2], kBSlot[i][3]))
				slot = i;
		}
		if (slot < 0)
		{
			static int s_unmatched = 0;
			static void *s_last = nullptr;
			if (card != s_last && s_unmatched < 12)
			{
				s_last = card;
				++s_unmatched;
				log("battle card %08x not placed: tex %08x at (%.1f, %.1f) -> (%.1f, %.1f), scale -> %.2f, dims %.1f, z %.2f",
				    id_of(card), texture_of(card), f32(card, kElementPos), f32(card, kElementPos + 4), tx, ty,
				    f32(card, kElementScaleTarget), f32(card, kElementDims), f32(card, kElementZ));
			}
			return;
		}
		// 1.48: guitar_battle morphs only the first card's position (no scale), so its scale target can be 0: the
		// size then comes from its current scale (user 2026-10-23: the bottom card stayed 64 px, far over its slot)
		float s = f32(card, kElementScaleTarget);
		if (s < 0.05f)
			s = f32(card, kElementScale);
		if (s < 0.05f)
			s = 1.0f;
		const float d = kBSlot[slot][4] / s;
		if (fabsf(f32(card, kElementDims) - d) > 0.05f)
			reinterpret_cast<SetDimsFn>(kSetDims)(card, nullptr, d, d, 0);
		// the bottom card in front, then the middle one, then the top one (user 2026-10-23: the middle item always
		// below the bottom one); relative to the z the game gave the card (battle_hud_2d_elements.z + 19), so the
		// cards stay above the slots however the battle layer is raised
		const float z = floorf(f32(card, kElementZ)) + (3 - slot % 3) * 0.02f;
		if (f32(card, kElementZ) != z)
			f32(card, kElementZ) = z;
	}

	// 1.40: the band bulb's popup; 1.58: WoR's (HUD_setup_band_mult_animation): it slides out from behind the score box
	// (from its spot + kBulbFrom at kBulbFromScale) in kBulbPopupTime, the orange glow sprite next to it flashing
	// 1.96 (user 2026-11-08: "the lightbulb needs an equivalent fade out effect just like fade in"): WoR's hide_band_mult is
	// the same 0.3 s move back to hide_pos (+118, +32) at hide_scale 0.5 (ghwor hud_widgets HUD_setup_band_mult_animation);
	// the DE blanks the bulb at once. `out`: the popup played backwards, the bulb texture kept until it ends, then blank
	// next: the texture the hide ends on (the DE's blank, or the next bulb, which then grows out)
	struct Grow { void *e = nullptr, *glow = nullptr; double t0 = 0.0; float sx = 1.0f, sy = 1.0f, x = 0.0f, y = 0.0f; bool out = false;
	              uint32_t next = 0; };
	Grow g_grow[4];
	bool g_bulb_blanking = false;   // our own blank write at the end of the hide (the texture hook lets it through)

	// the bulb's glow sibling (texture kBandBulbGlow, same parent)
	void *bulb_glow_of(void *e)
	{
		void *parent = *reinterpret_cast<void **>(field(e, kElementParent));
		if (!parent)
			return nullptr;
		for (void *c = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); c;
		     c = *reinterpret_cast<void **>(field(c, kElementNextSibling)))
			if (texture_of(c) == kBandBulbGlow)
				return c;
		return nullptr;
	}

	void bulb_grow(void *e, bool out = false)
	{
		Grow *slot = &g_grow[0];
		for (Grow &g : g_grow)
			if (g.e == e || !g.e)
			{
				slot = &g;
				break;
			}
		if (slot->e != e)
		{
			slot->sx = f32(e, kElementScale);
			slot->sy = f32(e, kElementScale + 4);
			slot->x = f32(e, kElementPos);
			slot->y = f32(e, kElementPos + 4);
			slot->glow = bulb_glow_of(e);
		}
		slot->e = e;
		slot->t0 = now();
		slot->out = out;
	}

	void bulb_frame(void *e)
	{
		for (Grow &g : g_grow)
		{
			if (g.e != e || g.t0 <= 0.0)
				continue;
			const double u = (now() - g.t0) / kBulbPopupTime;
			float k = 1.0f, flash = 0.0f;
			if (u < 1.0)
			{
				const float x = static_cast<float>(u);
				k = x * x * (3.0f - 2.0f * x);                    // smooth start and stop
				flash = 1.0f - x;
				if (g.out)
					k = 1.0f - k, flash = 0.0f;                   // the hide: back behind the score box, no flash
			}
			else
			{
				g.t0 = 0.0;
				if (g.out)
				{
					// hidden: put the texture the DE asked for on (blank, or the next bulb), then the bulb back to its spot
					// and size for the next show; a next bulb grows out right away
					const uint32_t next = g.next ? g.next : kBlankTex;
					g.out = false, g.next = 0;
					g_bulb_blanking = true;
					set_texture(e, next);
					g_bulb_blanking = false;
					if (next != kBlankTex)
					{
						g.t0 = now();
						continue;   // u = 0 next frame: the new bulb starts hidden behind the score box
					}
				}
			}
			const float s = kBulbFromScale + (1.0f - kBulbFromScale) * k;
			const float px = g.x + kBulbFrom[0] * (1.0f - k), py = g.y + kBulbFrom[1] * (1.0f - k);
			reinterpret_cast<SetScaleFn>(kSetScale)(e, nullptr, g.sx * s, g.sy * s, 0, 0);
			reinterpret_cast<SetPosFn>(kSetPos)(e, nullptr, px, py, 1);
			if (g.glow)
			{
				reinterpret_cast<SetScaleFn>(kSetScale)(g.glow, nullptr, g.sx * s, g.sy * s, 0, 0);
				reinterpret_cast<SetPosFn>(kSetPos)(g.glow, nullptr, px, py, 1);
				set_alpha(g.glow, flash);
			}
		}
	}

