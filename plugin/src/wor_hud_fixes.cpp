	void level_point(float level, float &x, float &y)
	{
		const float f = level * kLevelSteps;
		int i = static_cast<int>(f);
		i = i < 0 ? 0 : i >= kLevelSteps ? kLevelSteps - 1 : i;
		const float t = f - i;
		x = kLevelPt[i][0] + (kLevelPt[i + 1][0] - kLevelPt[i][0]) * t;
		y = kLevelPt[i][1] + (kLevelPt[i + 1][1] - kLevelPt[i][1]) * t;
	}

	// a new clip window (new song / HUD): find the effect sprites among its siblings by their texture names
	void discover(void *clip, void *fill)
	{
		g_sp = StarPower();
		g_sp.clip = clip;
		g_sp.fill = fill;
		g_sp.parent = *reinterpret_cast<void **>(field(clip, kElementParent));
		if (!g_sp.parent)
			return;
		int bursts = 0;
		for (void *e = *reinterpret_cast<void **>(field(g_sp.parent, kElementFirstChild)); e;
		     e = *reinterpret_cast<void **>(field(e, kElementNextSibling)))
		{
			const uint32_t t = texture_of(e);
			for (int k = 0; k < 3; ++k)
				if (t == kGlowTex[k])
					g_sp.glow[k] = e;
			if (t == kBall[0] && bursts < 3)
				g_sp.burst[bursts++] = e;
			if (t == kStarBar)
				g_sp.star_bar = e;
			else if (t == kStarLead)
				g_sp.star_lead = e;
			else if (t == kProgFill)
				g_sp.prog_fill = e;
			else if (t == kProgLead)
				g_sp.prog_lead = e;
			else if (t == kStarFire[0])
				g_sp.star_fire = e;
			void *child = *reinterpret_cast<void **>(field(e, kElementFirstChild));
			if (e != clip && child && texture_of(child) == kSpFull && g_sp.feathers < kFeathers)
				g_sp.feather[g_sp.feathers++] = e;
		}
		bool ok = bursts == 3;
		for (void *g : g_sp.glow)
			ok = ok && g && f32(g, kElementAlpha) == 0.0f;       // the desc starts them hidden
		ok = ok && f32(g_sp.parent, kElementAlpha) == 1.0f;       // and their container visible
		g_sp.effects = ok;
		log("star power effects: %s (glows %p %p %p, bursts %d, feathers %d)", ok ? "found" : "not found, fill only",
		    g_sp.glow[0], g_sp.glow[1], g_sp.glow[2], bursts, g_sp.feathers);
		log("score box effects: star bar %p lead %p, song line %p lead %p, star fire %p", g_sp.star_bar, g_sp.star_lead,
		    g_sp.prog_fill, g_sp.prog_lead, g_sp.star_fire);
	}

	float level_y(float level)
	{
		if (level <= 0.5f)
			return kLevel0 + (kLevel50 - kLevel0) * (level / 0.5f);
		return kLevel50 + (kLevel100 - kLevel50) * ((level - 0.5f) / 0.5f);
	}

	// the feather windows: bands of kFeatherH / kFeathers above the level, each showing the fill's texture faded (the
	// desc gives each band's fill its alpha), so the fill's top edge is a soft gradient instead of a pixel-hard cut
	void place_feathers()
	{
		const auto set_pos = reinterpret_cast<SetPosFn>(kSetPos);
		const auto set_dims = reinterpret_cast<SetDimsFn>(kSetDims);
		const bool hidden = g_sp.level <= 0.001f || g_sp.level >= 0.999f;
		const float top = hidden ? 0.0f : level_y(g_sp.level), band = kFeatherH / kFeathers;
		for (int k = 0; k < g_sp.feathers; ++k)
		{
			void *win = g_sp.feather[k];
			void *fill = *reinterpret_cast<void **>(field(win, kElementFirstChild));
			const float hi = top - (k + 1) * band, lo = top;   // nested: every window ends at the level
			const float t = hi < kClipY ? kClipY : hi;
			if (hidden || !fill || lo - t <= 0.0f)
			{
				set_dims(win, nullptr, kClipW, 0.0f, 0);
				continue;
			}
			set_tube_texture(fill, texture_of(g_sp.fill));
			set_dims(win, nullptr, kClipW, lo - t, 0);
			set_pos(win, nullptr, kClipX, t, 1);
			set_pos(fill, nullptr, kFillX - kClipX, kFillY - t, 1);
		}
	}

	// the clip window's top edge is the displayed level (none at 0, unclipped at 100%); it keeps its bottom
	void place_fill()
	{
		const auto set_pos = reinterpret_cast<SetPosFn>(kSetPos);
		const auto set_dims = reinterpret_cast<SetDimsFn>(kSetDims);
		const float level = g_sp.level, bottom = kClipY + kClipH;
		const float top = level >= 0.999f ? kClipY : level <= 0.001f ? bottom : level_y(level);
		set_dims(g_sp.clip, nullptr, kClipW, bottom - top, 0);
		set_pos(g_sp.clip, nullptr, kClipX, top, 1);
		set_pos(g_sp.fill, nullptr, kFillX - kClipX, kFillY - top, 1);
	}

	// the star bar's and the song line's dots (WoR's HUD_star_lead): comets with the dot at kCometHead of their width,
	// placed on the tip of the bar the DE grows (scale / dims set by its own scripts); the star's fire glow loop + swell
	void place_score_effects(double t)
	{
		const auto set_pos = reinterpret_cast<SetPosFn>(kSetPos);
		if (g_sp.star_bar && g_sp.star_lead)
		{
			const float w = f32(g_sp.star_bar, kElementDims) * f32(g_sp.star_bar, kElementScale);
			const float x = f32(g_sp.star_bar, kElementPos) + w - (kCometHead - 0.5f) * 64.0f * kStarLeadS;
			set_pos(g_sp.star_lead, nullptr, x, f32(g_sp.star_bar, kElementPos + 4), 1);
			set_alpha(g_sp.star_lead, w > 2.0f ? 1.0f : 0.0f);
		}
		if (g_sp.prog_fill && g_sp.prog_lead)
		{
			const float w = f32(g_sp.prog_fill, kElementDims);
			const float x = f32(g_sp.prog_fill, kElementPos) + w - (kCometHead - 0.5f) * 64.0f * kProgLeadS;
			set_pos(g_sp.prog_lead, nullptr, x, f32(g_sp.prog_fill, kElementPos + 4) + f32(g_sp.prog_fill, kElementDims + 4) * 0.5f, 1);
			set_alpha(g_sp.prog_lead, w > 2.0f ? 1.0f : 0.0f);
		}
		if (g_sp.star_fire)
		{
			set_texture(g_sp.star_fire, kStarFire[static_cast<long long>(t * kFireFps) % (sizeof(kStarFire) / sizeof(kStarFire[0]))]);
			set_alpha(g_sp.star_fire, kFireBase + kFireAmp * static_cast<float>(sin(t * 6.2831853 * kFireHz)));
		}
	}

	// every frame (from the clip window's own update, game thread)
	void sp_frame()
	{
		if (*reinterpret_cast<void **>(field(g_sp.clip, kElementFirstChild)) != g_sp.fill ||
		    !is_tube_texture(texture_of(g_sp.fill)))
		{
			g_sp = StarPower();   // not our window any more
			return;
		}
		const double t = now();
		if (g_sp.glide_dur > 0.0)
		{
			const double u = (t - g_sp.glide_t0) / g_sp.glide_dur;
			g_sp.level = u >= 1.0 ? g_sp.target : g_sp.from + (g_sp.target - g_sp.from) * static_cast<float>(u);
			if (u >= 1.0)
				g_sp.glide_dur = 0.0;
		}
		place_fill();
		place_score_effects(t);
		const bool shown = g_sp.level > 0.001f;
		if (g_sp.ready && shown)
			set_tube_texture(g_sp.fill, kPlasma[static_cast<long long>(t * kPlasmaFps) % (sizeof(kPlasma) / sizeof(kPlasma[0]))]);
		place_feathers();
		if (!g_sp.effects)
			return;
		const auto set_pos = reinterpret_cast<SetPosFn>(kSetPos);
		float x, y;
		level_point(g_sp.level, x, y);
		set_alpha(g_sp.glow[0], shown ? kGlowAlpha[0] : 0.0f);
		for (int k = 1; k < 3; ++k)
		{
			if (g_sp.ready && shown)
				set_pos(g_sp.glow[k], nullptr, x, y, 1);
			set_alpha(g_sp.glow[k], g_sp.ready && shown ? kGlowAlpha[k] : 0.0f);
		}
		if (g_sp.burst_t0 >= 0.0)
		{
			const double dt = t - g_sp.burst_t0;
			const bool on = dt < kBurstEnd;
			const float fade = dt <= kBurstHold ? 1.0f : static_cast<float>(1.0 - (dt - kBurstHold) / (kBurstEnd - kBurstHold));
			for (int k = 0; k < 3; ++k)
			{
				if (on)
				{
					set_texture(g_sp.burst[k], kBall[(static_cast<int>(dt * kBallFps) + k * 5) % 16]);
					set_pos(g_sp.burst[k], nullptr, x + kBurstOff[k][0], y + kBurstOff[k][1], 1);
				}
				set_alpha(g_sp.burst[k], on ? fade : 0.0f);
			}
			if (!on)
				g_sp.burst_t0 = -1.0;
		}
	}

