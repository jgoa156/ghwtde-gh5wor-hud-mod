	void log(const char *fmt, ...)
	{
		if (!g_log)
			return;
		va_list ap;
		va_start(ap, fmt);
		vfprintf(g_log, fmt, ap);
		va_end(ap);
		fputc('\n', g_log);
		fflush(g_log);
	}

	bool is_ours(uint32_t texture)
	{
		for (uint32_t t : kOurLights)
			if (t == texture)
				return true;
		return false;
	}

	uint32_t texture_of(void *element)
	{
		return *reinterpret_cast<uint32_t *>(static_cast<uint8_t *>(element) + kElementTexture);
	}

	bool is_our_fill(uint32_t texture)
	{
		for (const auto &p : kSpFill)
			if (p[1] == texture)
				return true;
		return false;
	}

	bool is_plasma(uint32_t t)
	{
		for (uint32_t p : kPlasma)
			if (p == t)
				return true;
		return false;
	}

	// replaces the two SP tube SetTexture calls: same calling convention (thiscall, one stack argument)
	void __fastcall sp_set_texture_hook(void *element, void *edx, uint32_t texture)
	{
		const uint32_t current = element ? texture_of(element) : 0;
		if (element && (is_our_fill(current) || current == kSpFull || current == kSpFullB || is_plasma(current)))
		{
			for (const auto &p : kSpFill)
			{
				if (p[0] == texture)
				{
					texture = p[1];
					break;
				}
			}
		}
		else if (element && (current == kVsFill[0][1] || current == kVsFill[1][1]))
		{
			// 1.35: multiplayer tubes (tools/wor_versus.py): WoR's fill under their own names, no smooth fill
			for (const auto &p : kVsFill)
			{
				if (p[0] == texture)
				{
					texture = p[1];
					break;
				}
			}
		}
		reinterpret_cast<SetTextureFn>(kSetTexture)(element, edx, texture);
	}

	uint8_t *field(void *base, size_t off) { return static_cast<uint8_t *>(base) + off; }

	// 1.38: our meter = its first light shows one of our light names (the desc starts it on WoR_HUD_light_0), or a
	// sibling shows one of our multiplier badges. The multiplayer meters were missed by the first test alone (user
	// test 2026-10-22: the DE's stock light textures on them, as if ours didn't load), so their lights kept the
	// DE's names.
	float &f32(void *e, size_t off);

	// 1.45: our multiplier desc (wor_mult_1g / wor_mult_mp: the 1-player one on every highway) by its elements, not by
	// the textures they show: its badge is the only element at z 0.05 with 256x256 dims (under the highway surface),
	// its lights are the badge's siblings. Recognising them by texture failed whenever the DE wrote its own light /
	// instrument icon name first (user 2026-10-23: a random highway's streak meter kept the stock texture until it
	// reloaded, sometimes with the instrument icon)
	bool is_our_badge(void *e)
	{
		return fabsf(f32(e, kElementZ) - 0.05f) < 1e-4f && f32(e, kElementDims) == 256.0f &&
		       f32(e, kElementDims + 4) == 256.0f;
	}

	bool in_our_mult(void *e)
	{
		if (!e)
			return false;
		if (is_our_badge(e))
			return true;
		void *parent = *reinterpret_cast<void **>(field(e, kElementParent));
		if (!parent)
			return false;
		for (void *c = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); c;
		     c = *reinterpret_cast<void **>(field(c, kElementNextSibling)))
			if (is_our_badge(c))
				return true;
		return false;
	}

	bool our_meter(void **elements)
	{
		if (elements[0] == nullptr)
			return false;
		if (in_our_mult(elements[0]))
			return true;
		for (int k = 0; k < 5; ++k)
			if (elements[k] && is_ours(texture_of(elements[k])))
				return true;
		if (void *parent = *reinterpret_cast<void **>(field(elements[0], kElementParent)))
			for (void *c = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); c;
			     c = *reinterpret_cast<void **>(field(c, kElementNextSibling)))
				for (uint32_t m : kOurMult)
					if (texture_of(c) == m)
						return true;
		return false;
	}

	int g_light_logs = 0;
	int g_streak[4] = {};      // 1.48: each player's note streak, as the DE last gave it to a streak meter

	void __fastcall set_lights_hook(void *widget, void *edx, int streak)
	{
		const int who = *reinterpret_cast<int *>(field(widget, 0xc)) - 1;
		if (who >= 0 && who < 4)
			g_streak[who] = streak;
		void **elements = reinterpret_cast<void **>(field(widget, 0x1c));
		if (!our_meter(elements))
		{
			g_original(widget, edx, streak);
			return;
		}
		const int player = *reinterpret_cast<int *>(field(widget, 0xc)) - 1;
		const int mult = reinterpret_cast<GetMultiplierFn>(kGetMultiplier)(*reinterpret_cast<void **>(kPlayerInfo), nullptr, player, 1);
		const bool sp = reinterpret_cast<IsStarPowerFn>(kIsStarPower)(*reinterpret_cast<void **>(kStarPower), nullptr, player);
		const int set = sp ? 4 : mult >= 4 ? 3 : mult == 3 ? 2 : mult == 2 ? 1 : 0;   // pink, orange, green, purple, blue
		if (g_light_logs < 8 && streak > 0)
		{
			++g_light_logs;
			log("streak lights: widget %p player %d streak %d mult %d sp %d -> set %d", widget, player + 1, streak, mult, sp, set);
		}

		// same mark maths as the game: 10 marks over 5 lights, 2 marks per light
		int s = streak < 0 ? 0 : streak > 30 ? 30 : streak;
		int marks = s % 10;
		if (s > 0 && marks == 0)
			marks = 10;
		const int full = static_cast<int>(marks * *reinterpret_cast<const double *>(kHalf));
		const int half = full + (marks & 1);
		const auto set_texture = reinterpret_cast<SetTextureFn>(kSetTexture);
		for (int k = 0; k < 5; ++k)
			set_texture(elements[k], nullptr, kLights[set][k < full ? 2 : k < half ? 1 : 0]);
	}

	bool sites_match()
	{
		for (const Site &s : kSites)
		{
			if (memcmp(reinterpret_cast<const void *>(s.addr), s.bytes, s.len) != 0)
			{
				log("inert: %s at 0x%08x does not match this game build", s.what, static_cast<unsigned>(s.addr));
				return false;
			}
		}
		if (*reinterpret_cast<const double *>(kHalf) != 0.5)
		{
			log("inert: constant at 0x%08x is not 0.5", static_cast<unsigned>(kHalf));
			return false;
		}
		return true;
	}

	bool install_set_lights()
	{
		// trampoline: the first 5 bytes (push ebx; push ebp; push esi; mov esi, ecx) + jmp back
		uint8_t *tramp = static_cast<uint8_t *>(VirtualAlloc(nullptr, 16, MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE));
		if (!tramp)
			return false;
		memcpy(tramp, reinterpret_cast<const void *>(kSetLights), 5);
		tramp[5] = 0xE9;
		*reinterpret_cast<int32_t *>(tramp + 6) = static_cast<int32_t>((kSetLights + 5) - reinterpret_cast<uintptr_t>(tramp + 10));
		g_original = reinterpret_cast<SetLightsFn>(tramp);

		DWORD old = 0;
		if (!VirtualProtect(reinterpret_cast<void *>(kSetLights), 5, PAGE_EXECUTE_READWRITE, &old))
			return false;
		uint8_t *p = reinterpret_cast<uint8_t *>(kSetLights);
		p[0] = 0xE9;
		*reinterpret_cast<int32_t *>(p + 1) = static_cast<int32_t>(reinterpret_cast<uintptr_t>(&set_lights_hook) - (kSetLights + 5));
		VirtualProtect(p, 5, old, &old);
		FlushInstructionCache(GetCurrentProcess(), p, 5);
		return true;
	}

	uint32_t read32(uintptr_t a) { return *reinterpret_cast<const uint32_t *>(a); }

	void write32(uintptr_t a, uint32_t v)
	{
		DWORD old = 0;
		VirtualProtect(reinterpret_cast<void *>(a), 4, PAGE_EXECUTE_READWRITE, &old);
		*reinterpret_cast<uint32_t *>(a) = v;
		VirtualProtect(reinterpret_cast<void *>(a), 4, old, &old);
		FlushInstructionCache(GetCurrentProcess(), reinterpret_cast<void *>(a), 4);
	}

	bool readable(uint32_t a, uint32_t n)
	{
		MEMORY_BASIC_INFORMATION mi{};
		for (uint32_t p = a; p < a + n; p = static_cast<uint32_t>(reinterpret_cast<uintptr_t>(mi.BaseAddress) + mi.RegionSize))
		{
			if (!VirtualQuery(reinterpret_cast<void *>(static_cast<uintptr_t>(p)), &mi, sizeof(mi)) || mi.State != MEM_COMMIT ||
			    (mi.Protect & (PAGE_NOACCESS | PAGE_GUARD)))
				return false;
		}
		return true;
	}

	// Gives the unload loop the add loop's bounds (read now: the DE patches them after the plugin loads).
	void fix_font_bounds()
	{
		const uint32_t s = read32(kAddLoopStart), e = read32(kAddLoopEnd);
		const uint32_t us = read32(kUnloadStarts[0]), ue = read32(kUnloadEnd);
		log("font table: add loop %08x..%08x, unload loop %08x..%08x", s, e, us, ue);
		if (us == s && ue == e)
		{
			log("font table: consistent, nothing to do");
			return;
		}
		if (e <= s || (e - s) % kFontEntry != 0 || !readable(s, e - s))
		{
			log("font table: add loop bounds look wrong, left alone");
			return;
		}
		for (uintptr_t a : kUnloadStarts)
			if (read32(a) == kFontTable || read32(a) == us)
				write32(a, s);
		write32(kUnloadEnd, e);
		log("font table: unload loop now %08x..%08x (%u slots)", read32(kUnloadStarts[0]), read32(kUnloadEnd), (e - s) / kFontEntry);
	}

