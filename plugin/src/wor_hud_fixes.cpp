	void battle_needle(void *needle)
	{
		void *parent = *reinterpret_cast<void **>(field(needle, kElementParent));
		if (!parent || texture_of(needle) != kBNeedleTex)
			return;
		void *src = nullptr;
		for (void *c = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); c && !src;
		     c = *reinterpret_cast<void **>(field(c, kElementNextSibling)))
			if (id_of(c) == kBNeedleId[0] || id_of(c) == kBNeedleId[1])
				src = c;
		if (!src)
			return;
		g_battle_seen = now();
		const float *swing = reinterpret_cast<const float *>(kNeedleSwing);
		const float a = *reinterpret_cast<const uint8_t *>(kModeFlag) ? swing[0] : swing[1];
		const bool p2 = id_of(src) == kBNeedleId[1];
		const float deg = f32(src, kElementRot) * 57.2957795f;   // 0x465ab0: the same formula for both players
		float h = 1.0f + deg / a;
		static bool s_side_logged[2] = {};
		if (!s_side_logged[p2] && (deg > 5.0f || deg < -5.0f))
		{
			s_side_logged[p2] = true;
			log("battle needle P%d: deg %.1f -> health %.2f", p2 ? 2 : 1, deg, 1.0f + deg / a);
		}
		h = h < 0.0f ? 0.0f : h > 2.0f ? 2.0f : h;
		const int i = h < 2.0f / 3.0f ? 0 : h < 4.0f / 3.0f ? 1 : 2;
		float t = (h - i * (2.0f / 3.0f)) * 1.5f;
		t = t < 0.0f ? 0.0f : t > 1.0f ? 1.0f : t;
		// 1.50: the tween target too (user 2026-10-23: the needle stayed at its health-1 spot whatever the LEDs showed;
		// since 1.41 move_2d_elements_to_default tweens the battle pieces to their defaults, and an element under a tween
		// is put back on its target every frame, overwriting the position written here)
		const float nx = f32(src, kElementPos) + kBNeedleD[i][0] + (kBNeedleD[i + 1][0] - kBNeedleD[i][0]) * t;
		const float ny = f32(src, kElementPos + 4) + kBNeedleD[i][1] + (kBNeedleD[i + 1][1] - kBNeedleD[i][1]) * t;
		f32(needle, kElementPos) = f32(needle, kElementPosTarget) = nx;
		f32(needle, kElementPos + 4) = f32(needle, kElementPosTarget + 4) = ny;
		if (!g_bneedle_logged)
		{
			g_bneedle_logged = true;
			log("battle needle: stand-in %08x at (%.1f, %.1f), rot %.2f deg, swing %.0f -> health %.2f",
			    id_of(src), f32(src, kElementPos), f32(src, kElementPos + 4), deg, a, h);
		}
		// 1.38: tracking log (user test 2026-10-22: red LED lit with the needle up at the red / yellow boundary): once
		// a second, the DE's angle, our health and zone, and the DE-driven siblings' alphas (its LED / BG layers)
		static double s_track_t = 0.0;
		static int s_track_logs = 0;
		if (s_track_logs < 120 && g_battle_seen - s_track_t >= 1.0)
		{
			s_track_t = g_battle_seen;
			++s_track_logs;
			char buf[256];
			int n = snprintf(buf, sizeof(buf), "battle track: deg %.1f health %.2f zone %d t %.2f | alphas", deg, h, i, t);
			for (void *c = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); c && n < 240;
			     c = *reinterpret_cast<void **>(field(c, kElementNextSibling)))
				if (c != needle && c != src && f32(c, kElementAlpha) > 0.01f)
					n += snprintf(buf + n, sizeof(buf) - n, " %08x=%.2f", texture_of(c), f32(c, kElementAlpha));
			log("%s", buf);
		}
		if ((deg < g_brot_lo - 2.0f || deg > g_brot_hi + 2.0f) && g_brange_logs < 24)
		{
			g_brot_lo = deg < g_brot_lo ? deg : g_brot_lo;
			g_brot_hi = deg > g_brot_hi ? deg : g_brot_hi;
			++g_brange_logs;
			log("battle needle: rot range now %.1f .. %.1f deg (swing %.0f)", g_brot_lo, g_brot_hi, a);
		}
	}

