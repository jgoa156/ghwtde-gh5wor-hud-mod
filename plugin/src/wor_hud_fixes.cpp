	// the 1-player engine on one tube: a new level / state from the DE (the widget hook, or a multiplayer tube's
	// level source)
	void tube_set(void *clip, void *fill, float level, bool charged)
	{
		g_spp = tube_for(clip);
		if (clip != g_sp.clip || fill != g_sp.fill)
			discover(clip, fill);
		// 1.70 (compare_wor 2026-10-28: active fill (50,111,120) vs WoR's (79,144,138)): the DE drops the _b texture once a
		// deployment drains below 50%, WoR keeps the charged plasma to the end. A charged meter only goes down by being
		// deployed, so the charged look stays until the tube is empty.
		// 1.86 (user 2026-10-30: quickplay showed the charged look at 25%): only while star power is really on; a
		// deployment that ended above 1% left the flag set, so the next phrase showed charged
		charged = charged || (g_sp.ready && level > 0.01f && star_power_on());
		// GH5's ready burst: the meter crosses into ready (not on the first update of a HUD, not on activation)
		if (g_sp.seen && charged && !g_sp.ready && level >= 0.49f && g_sp.effects)
			g_sp.burst_t0 = now();
		// GH5 jumps on phrase gains; small changes (whammy, drain: the DE updates ~10 times a second) glide over the
		// time since the previous update, so the bar moves every frame
		const double t = now();
		if (!g_sp.seen || (level > g_sp.level ? level - g_sp.level : g_sp.level - level) > kSnap)
		{
			g_sp.level = g_sp.from = level;
			g_sp.glide_dur = 0.0;
		}
		else
		{
			const double gap = t - g_sp.last_update;
			g_sp.from = g_sp.level;
			g_sp.glide_t0 = t;
			g_sp.glide_dur = gap < 1.0 / 60.0 ? 1.0 / 60.0 : gap > 0.25 ? 0.25 : gap;
		}
		g_sp.target = level;
		g_sp.last_update = t;
		g_sp.seen = true;
		g_sp.ready = charged;

		const auto set_scale = reinterpret_cast<SetScaleFn>(kSetScale);
		const auto set_dims = reinterpret_cast<SetDimsFn>(kSetDims);
		reinterpret_cast<SetTextureFn>(kSetTexture)(fill, nullptr, charged ? kSpFullB : kSpFull);   // plasma next frame
		// SetPos only moves the element now with a non-zero flag (0 = tween target)
		set_scale(fill, nullptr, kFillSX, kFillSY, 0, 0);
		set_dims(fill, nullptr, 64.0f, 256.0f, 0);
		sp_frame();   // window, texture, cap and glow right away
		if (!g_tube_logged)
		{
			g_tube_logged = true;
			// 1.72: gameplay has started (the first star power update of a song); tests/capture_band.py times its
			// 30 s window from this marker (user 2026-10-28: "your runs are going way past 30s")
			if (FILE *f = fopen("wor_hud_gameplay.flag", "w"))
				fclose(f);
			log("star power fill: smooth fill active (level %.2f, %s)", level, charged ? "charged" : "charging");
		}
	}

	// 1.46: a multiplayer tube (tools/wor_mp.py sp_desc): the DE's segments in a zero-size window (z kMpSrcZ) carry
	// the level, (default.x, default.y x fill) per segment; the tube's own fill (z kMpFillZ) sits in the clip window
	// beside it. Read every frame; the engine runs when the level or the charged state changes.
	int g_mp_tube_logs = 0;

	void mp_tube_source(void *src)
	{
		g_mp_seen = now();
		void *parent = *reinterpret_cast<void **>(field(src, kElementParent));
		if (!parent)
			return;
		void *clip = nullptr, *fill = nullptr;
		for (void *e = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); e && !clip;
		     e = *reinterpret_cast<void **>(field(e, kElementNextSibling)))
		{
			void *c = *reinterpret_cast<void **>(field(e, kElementFirstChild));
			if (e != src && c && fabsf(f32(c, kElementZ) - kMpFillZ) < 1e-4f)
				clip = e, fill = c;
		}
		if (!clip)
			return;
		float sum = 0.0f;
		int n = 0;
		bool charged = false;
		for (void *s = *reinterpret_cast<void **>(field(src, kElementFirstChild)); s;
		     s = *reinterpret_cast<void **>(field(s, kElementNextSibling)))
		{
			const float sx = f32(s, kElementScale), sy = f32(s, kElementScale + 4);
			float f = sx > 1e-4f ? sy / sx : 0.0f;
			sum += f < 0.0f ? 0.0f : f > 1.0f ? 1.0f : f;
			++n;
			const uint32_t t = texture_of(s);
			charged = charged || t == kSpFill[1][0] || t == kSpFill[1][1];
		}
		if (n == 0)
			return;
		const float level = sum / n;
		StarPower *s = tube_for(clip);
		if (s->clip == clip && s->seen && fabsf(level - s->target) < 1e-4f && charged == s->ready)
			return;
		tube_set(clip, fill, level, charged);
		if (g_mp_tube_logs < 6)
		{
			++g_mp_tube_logs;
			log("star power: multiplayer tube %p level %.2f (%d segments), %s", clip, level, n, charged ? "charged" : "charging");
		}
	}

	// 5-byte jmp at site to target; the first `len` bytes (whole instructions) move to a trampoline
	void *install_jmp(uintptr_t site, size_t len, void *target)
	{
		uint8_t *tramp = static_cast<uint8_t *>(VirtualAlloc(nullptr, 32, MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE));
		if (!tramp)
			return nullptr;
		memcpy(tramp, reinterpret_cast<const void *>(site), len);
		tramp[len] = 0xE9;
		*reinterpret_cast<int32_t *>(tramp + len + 1) = static_cast<int32_t>((site + len) - reinterpret_cast<uintptr_t>(tramp + len + 5));
		DWORD old = 0;
		if (!VirtualProtect(reinterpret_cast<void *>(site), len, PAGE_EXECUTE_READWRITE, &old))
			return nullptr;
		uint8_t *p = reinterpret_cast<uint8_t *>(site);
		p[0] = 0xE9;
		*reinterpret_cast<int32_t *>(p + 1) = static_cast<int32_t>(reinterpret_cast<uintptr_t>(target) - (site + 5));
		for (size_t i = 5; i < len; ++i)
			p[i] = 0x90;
		VirtualProtect(p, len, old, &old);
		FlushInstructionCache(GetCurrentProcess(), p, len);
		return tramp;
	}

	bool install_call(uintptr_t site, void *target)
	{
		DWORD old = 0;
		if (!VirtualProtect(reinterpret_cast<void *>(site), 5, PAGE_EXECUTE_READWRITE, &old))
			return false;
		uint8_t *p = reinterpret_cast<uint8_t *>(site);
		*reinterpret_cast<int32_t *>(p + 1) = static_cast<int32_t>(reinterpret_cast<uintptr_t>(target) - (site + 5));
		VirtualProtect(p, 5, old, &old);
		FlushInstructionCache(GetCurrentProcess(), p, 5);
		return true;
	}

	// the score widget formats its number with _snwprintf(buf, 10, L"%d", value); with the WoR HUD up the number gets
	// thousands separators (WoR: "84,225"). Falls back to the game's own call when it would not fit the 10 wchar buffer.
	int __cdecl score_text_hook(wchar_t *buf, size_t count, const wchar_t *fmt, int value)
	{
		const auto orig = reinterpret_cast<int(__cdecl *)(wchar_t *, size_t, const wchar_t *, int)>(kSnwprintf);
		// 1.39: also in the 2-player modes (no 1-player star bar there): while our versus needle or battle meter is up;
		// 1.53 (user 2026-10-25: no separators in band): and while a multiplayer star power tube is up; 1.56: or any
		// of our score boxes (vocals)
		const bool ours = any_star_bar() || now() - g_vs_seen < 2.0 || now() - g_battle_seen < 2.0 ||
		                  now() - g_mp_seen < 2.0 || now() - g_score_seen < 2.0;
		if (!ours || value < 0 || count < 2)
			return orig(buf, count, fmt, value);
		wchar_t digits[12];
		int n = 0;
		for (unsigned v = static_cast<unsigned>(value); n < 11; v /= 10)
		{
			digits[n++] = static_cast<wchar_t>(L'0' + v % 10);
			if (v < 10)
				break;
		}
		const int len = n + (n - 1) / 3;
		if (static_cast<size_t>(len) + 1 > count)
			return orig(buf, count, fmt, value);
		int o = 0;
		for (int i = n - 1; i >= 0; --i)
		{
			buf[o++] = digits[i];
			if (i > 0 && i % 3 == 0)
				buf[o++] = L',';
		}
		buf[o] = 0;
		return o;
	}

