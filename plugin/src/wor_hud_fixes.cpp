	// the level, (default.x, default.y x fill) per segment; the tube's own fill (z kMpFillZ) sits in the clip window
	// beside it. Read every frame; the engine runs when the level or the charged state changes.
	int g_mp_tube_logs = 0;

	void mp_tube_source(void *src)
	{
		void *parent = *reinterpret_cast<void **>(field(src, kElementParent));
		if (!parent)
			return;
		void *clip = nullptr, *fill = nullptr;
		for (void *e = *reinterpret_cast<void **>(field(parent, kElementFirstChild)); e && !clip;
		     e = *reinterpret_cast<void **>(field(e, kElementNextSibling)))
		{
			void *c = *reinterpret_cast<void **>(field(e, kElementFirstChild));
			if (e != src && c && fabsf(f32(c, kElementZ) - kMpFillZ) < 1e-4f)
				clip = e, fill = c;
		}
		if (!clip)
			return;
		float sum = 0.0f;
		int n = 0;
		bool charged = false;
		for (void *s = *reinterpret_cast<void **>(field(src, kElementFirstChild)); s;
		     s = *reinterpret_cast<void **>(field(s, kElementNextSibling)))
		{
			const float sx = f32(s, kElementScale), sy = f32(s, kElementScale + 4);
			float f = sx > 1e-4f ? sy / sx : 0.0f;
			sum += f < 0.0f ? 0.0f : f > 1.0f ? 1.0f : f;
			++n;
			const uint32_t t = texture_of(s);
			charged = charged || t == kSpFill[1][0] || t == kSpFill[1][1];
		}
		if (n == 0)
			return;
		const float level = sum / n;
		StarPower *s = tube_for(clip);
		if (s->clip == clip && s->seen && fabsf(level - s->target) < 1e-4f && charged == s->ready)
			return;
		tube_set(clip, fill, level, charged);
		if (g_mp_tube_logs < 6)
		{
			++g_mp_tube_logs;
			log("star power: multiplayer tube %p level %.2f (%d segments), %s", clip, level, n, charged ? "charged" : "charging");
		}
	}

	// 5-byte jmp at site to target; the first `len` bytes (whole instructions) move to a trampoline
	void *install_jmp(uintptr_t site, size_t len, void *target)
	{
		uint8_t *tramp = static_cast<uint8_t *>(VirtualAlloc(nullptr, 32, MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE));
		if (!tramp)
			return nullptr;
		memcpy(tramp, reinterpret_cast<const void *>(site), len);
		tramp[len] = 0xE9;
		*reinterpret_cast<int32_t *>(tramp + len + 1) = static_cast<int32_t>((site + len) - reinterpret_cast<uintptr_t>(tramp + len + 5));
		DWORD old = 0;
		if (!VirtualProtect(reinterpret_cast<void *>(site), len, PAGE_EXECUTE_READWRITE, &old))
			return nullptr;
		uint8_t *p = reinterpret_cast<uint8_t *>(site);
		p[0] = 0xE9;
		*reinterpret_cast<int32_t *>(p + 1) = static_cast<int32_t>(reinterpret_cast<uintptr_t>(target) - (site + 5));
		for (size_t i = 5; i < len; ++i)
			p[i] = 0x90;
		VirtualProtect(p, len, old, &old);
		FlushInstructionCache(GetCurrentProcess(), p, len);
		return tramp;
	}

	bool install_call(uintptr_t site, void *target)
	{
		DWORD old = 0;
		if (!VirtualProtect(reinterpret_cast<void *>(site), 5, PAGE_EXECUTE_READWRITE, &old))
			return false;
		uint8_t *p = reinterpret_cast<uint8_t *>(site);
		*reinterpret_cast<int32_t *>(p + 1) = static_cast<int32_t>(reinterpret_cast<uintptr_t>(target) - (site + 5));
		VirtualProtect(p, 5, old, &old);
		FlushInstructionCache(GetCurrentProcess(), p, 5);
		return true;
	}

	// the score widget formats its number with _snwprintf(buf, 10, L"%d", value); with the WoR HUD up the number gets
	// thousands separators (WoR: "84,225"). Falls back to the game's own call when it would not fit the 10 wchar buffer.
	int __cdecl score_text_hook(wchar_t *buf, size_t count, const wchar_t *fmt, int value)
	{
		const auto orig = reinterpret_cast<int(__cdecl *)(wchar_t *, size_t, const wchar_t *, int)>(kSnwprintf);
		// 1.39: also in the 2-player modes (no 1-player star bar there): while our versus needle or battle meter is up
		const bool ours = any_star_bar() || now() - g_vs_seen < 2.0 || now() - g_battle_seen < 2.0;
		if (!ours || value < 0 || count < 2)
			return orig(buf, count, fmt, value);
		wchar_t digits[12];
		int n = 0;
		for (unsigned v = static_cast<unsigned>(value); n < 11; v /= 10)
		{
			digits[n++] = static_cast<wchar_t>(L'0' + v % 10);
			if (v < 10)
				break;
		}
		const int len = n + (n - 1) / 3;
		if (static_cast<size_t>(len) + 1 > count)
			return orig(buf, count, fmt, value);
		int o = 0;
		for (int i = n - 1; i >= 0; --i)
		{
			buf[o++] = digits[i];
			if (i > 0 && i % 3 == 0)
				buf[o++] = L',';
		}
		buf[o] = 0;
		return o;
	}

	// Create2DParticleSystem config slot (esi): +0x10/+0x14 start_scale, +0x20/+0x24 end_scale, +0x44 material,
	// +0x5c start_color (r, g, b, a bytes). With the WoR HUD up, the star power phrase burst (GuitarEvent_StarSequenceBonus)
	// gets WoR's particle sizes: Star01 0.55 -> 0.25, Star02 0.5 -> 0.125 at half alpha, its cyan Spark01 1.5 -> 0.5
	// (only that one: the gem explosions use Spark01 at other sizes). A mod cannot redefine the script itself.
	void *g_particle_tramp = nullptr;

	void __cdecl particle_fix(uint8_t *cfg)
	{
		if (!any_star_bar() || !cfg)
			return;
		float *ss = reinterpret_cast<float *>(cfg + 0x10), *es = reinterpret_cast<float *>(cfg + 0x20);
		const uint32_t mat = *reinterpret_cast<uint32_t *>(cfg + 0x44);
		if (mat == 0xab62af58 && ss[0] > 0.54f && ss[0] < 0.56f)            // sys_Particle_Star01
			ss[0] = ss[1] = 0.25f;
		else if (mat == 0x49757c01 && ss[0] > 0.49f && ss[0] < 0.51f)       // sys_Particle_Star02
		{
			ss[0] = ss[1] = 0.125f;
			es[0] = es[1] = 0.15f;
			cfg[0x5f] = static_cast<uint8_t>(cfg[0x5f] / 2);
		}
		else if (mat == 0xc5c51fee && ss[0] > 1.49f && ss[0] < 1.51f)       // sys_Particle_Spark01 (burst only)
			ss[0] = ss[1] = 0.5f;
	}

